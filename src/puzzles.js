function solvePuzzle() {
    const puzzleList = Alpine.store("puzzleList");
    const entry = puzzleList.current;

    if (entry instanceof ArchipelagoPuzzle && entry.genre === "keen" && isApReady()) {
        // The native Solve function operates on whatever subset of clues is
        // currently visible, which for any non-final stage is deliberately
        // under-constrained (that's the whole point of the progressive
        // reveal) -- it will therefore usually just fail with an error, or
        // in rare cases "solve" a puzzle that still has undiscovered digit
        // groups without going through the normal per-stage checks. Disable
        // it entirely for progressive Keen puzzles rather than risk either.
        Alpine.store("errorMessage").show(
            "Solve is disabled for progressive Keen puzzles -- use logical deduction to reveal each digit group."
        );
        return;
    }

    sendMessage("solvePuzzle");

    // Mark puzzle as solved regardless of whether the puzzle was actually solved

    Alpine.store("puzzleList").markSolved()
}

