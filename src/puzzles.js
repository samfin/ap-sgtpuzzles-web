function syncAPStatus() {
    const puzzleList = Alpine.store("puzzleList");

    if (!isApReady()) {
        puzzleList.resort();
        return;
    };

    const gamesaves = Alpine.store("gamesaves");

    let allSolved = true;
    let currentFile = gamesaves.current;

    let fileDirty = false;

    let newRemoteSolves = {};
    let anyNewRemoteSolves = false;

    for (let entry of puzzleList.entries) {
        let dirty = false;

        if (entry.genre === "keen") {
            // -- Progressive Clue Set item / Digit Group locations --

            const itemId = itemNameToId(`Puzzle ${entry.index} Clue Set`);
            const newClueSetCount = (itemId === undefined || itemId === null) ? 0
                : client.items.received.filter(e => e.id === itemId).length;

            if (newClueSetCount !== entry.clueSetCount) {
                entry.clueSetCount = newClueSetCount;
                entry.locked = (newClueSetCount === 0);
                dirty = true;

                // If this puzzle is currently open and already resolved,
                // capture the player's moves and move it to the new stage.
                if (entry === puzzleList.current && entry.resolved) {
                    savePuzzleData();
                    entry.reloadAtCurrentStage();
                }
            }

            const newCheckedStages = new Set();
            for (let k = 0; k < entry.digitGroupCount; k++) {
                const locationId = locationNameToId(`Puzzle ${entry.index} Digit Group ${k + 1}`);
                if (locationId !== undefined && locationId !== null
                    && client.room.checkedLocations.includes(locationId)) {
                    newCheckedStages.add(k);
                }
            }
            if (newCheckedStages.size !== entry.checkedStages.size) {
                dirty = true;
            }
            entry.checkedStages = newCheckedStages;

            const nowSolved = entry.checkedStages.size >= entry.digitGroupCount;
            if (nowSolved !== entry.solved) {
                entry.solved = nowSolved;
                dirty = true;
            }
            entry.collected = entry.solved;
            if (!entry.solved) allSolved = false;
        } else {
            // Legacy single item/location genres -- this world only ever
            // emits Keen puzzles, but Freeplay/debug mode can still list
            // other genres, so keep the old behavior for those.
            let itemId = itemNameToId(`Puzzle ${entry.index}`);
            let locationId = locationNameToId(`Puzzle ${entry.index} Reward`);

            if (!entry.collected && client.room.checkedLocations.includes(locationId)) {
                entry.collected = true;
                dirty = true;
            } else if (!entry.collected) {
                allSolved = false;
            }

            if (entry.locked && hasItem(itemId)) {
                entry.locked = false;
                dirty = true;

                if (currentFile && currentFile.puzzleLocked[entry.index-1]) {
                    currentFile.puzzleLocked[entry.index-1] = false;
                    fileDirty = true;
                }
            }
        }

        if (dirty) {
            entry.updateState();
        }

        if (entry.solved && !(entry.index in remoteSolved)) {
            newRemoteSolves[entry.index] = 1;
            remoteSolved[entry.index] = 1;
            anyNewRemoteSolves = true;
        }
    }

    if (anyNewRemoteSolves) {
        console.log("newly solved: ", newRemoteSolves)
        let team = client.players.self.team
        let slot = client.players.self.slot
        let key = `sgtkeen_solves_${team}_${slot}`
        client.storage.prepare(key, {})
            .update(newRemoteSolves)
            .commit()
    }

    puzzleList.resort();

    if (fileDirty) {
        currentFile.save();
    }
}

